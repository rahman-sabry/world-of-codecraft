"""Bake the approved world (direction A, v3) into the mod: the static village (ground, buildings, props,
their shadows and night lights) pre-composited by the art's own compositor (compose3.py), day and night,
so Herdr only draws a few big images plus the live units.

  tools/village-art/build_assets.sh && tools/village-art/.venv/bin/python tools/bake_world.py

THEME=hiver (both commands) bakes the winter map from assets-hiver/ into art/monde-hiver/ instead, after checking
that its sprites keep the summer boxes and silhouettes (all but the bare trees'): the same layout, the same data.
Writes, under art/monde/:
  jour-<k>.png, nuit-<k>.png   the 3000x400 logical world cut in 1000-px-wide tiles (PNG at 2x: 2000x800)
  avant-<name>-<jour|nuit>.png front cut-outs: an object's own pixels taken from the baked world, drawn again
                               above units standing behind it (depth sorting without re-lighting anything)
  minicarte.png                the minimap
and monde-data.js (world size, tiles, cut-outs with their depth). The buildings are never re-rendered or
recoloured: every pixel comes from compose3.compose(), exactly as in mock-wide*.png, minus the old heroes."""
import json, os, sys
import numpy as np
from PIL import Image

MOD = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "mods", "world-of-codecraft")
ART = os.environ.get("ART") or os.path.join(os.path.dirname(os.path.abspath(__file__)), "village-art")
os.chdir(ART)
sys.path.insert(0, ART)
import compose2 as C2  # noqa: E402
import compose3 as C3  # noqa: E402
import theme  # noqa: E402

OUT = os.path.join(MOD, "art", theme.MONDE)
os.makedirs(OUT, exist_ok=True)
W, H = C3.W, C3.H
TILE = 1000
FRONT_V = 200  # objects whose base is lower on screen than this can stand in front of a unit


def save2(arr, path):
    Image.fromarray(arr).resize((arr.shape[1] * 2, arr.shape[0] * 2), Image.NEAREST).save(path, optimize=True)


class _Meta(dict):
    def __missing__(self, k):
        return {'w': 1, 'h': 1, 'ax': 0, 'ay': 0}  # the old demo heroes: dropped just below


if theme.HIVER:
    summer = json.load(open("assets/meta.json"))
    assert C2.META == summer, "the winter sprites' boxes differ from the summer ones"
    same = 0
    for name in summer:
        a = np.asarray(Image.open(f"assets/{name}.png"))[..., 3] > 0
        b = np.asarray(Image.open(f"{theme.ASSETS}{name}.png"))[..., 3] > 0
        assert name in ("b-tree-oak", "b-tree-autumn") or (a == b).all(), f"{name}: its winter silhouette differs"
        same += int((a == b).all())
    print(f"winter sprites: {len(summer)} boxes as in summer, {same} silhouettes as in summer (the others: bare trees)")

C2.META = _Meta(C2.META)
O, _E = C2.scene()
O = [o for o in O if o[0].startswith("b-")]  # the static world only: no heroes, no hero effects
day = C3.compose(False, O, [])
night = C3.compose(True, O, [])

tiles = []
for k, x in enumerate(range(0, W, TILE)):
    save2(day[:, x:x + TILE], os.path.join(OUT, f"jour-{k}.png"))
    save2(night[:, x:x + TILE], os.path.join(OUT, f"nuit-{k}.png"))
    tiles.append({"k": k, "x": x, "w": min(TILE, W - x)})

fronts = []
seen = {}
for (name, u, v, dp, _extra) in O:
    if v < FRONT_V:
        continue
    m = C2.META[name]
    c = C3.load(name)
    x0, y0 = int(u - m["ax"]), int(v - m["ay"])
    hh, ww = c.shape[:2]
    xs0, ys0, xs1, ys1 = max(0, x0), max(0, y0), min(W, x0 + ww), min(H, y0 + hh)
    if xs1 <= xs0 or ys1 <= ys0:
        continue
    a = c[ys0 - y0:ys1 - y0, xs0 - x0:xs1 - x0, 3] > 0
    n = seen.get(name, 0)
    seen[name] = n + 1
    key = name[2:] + (f"-{n}" if n else "")
    for tag, img in (("jour", day), ("nuit", night)):
        cut = np.zeros((ys1 - ys0, xs1 - xs0, 4), np.uint8)
        cut[..., :3] = img[ys0:ys1, xs0:xs1]
        cut[..., 3] = np.where(a, 255, 0)
        save2(cut, os.path.join(OUT, f"avant-{key}-{tag}.png"))
    fronts.append({"key": key, "x": xs0, "y": ys0, "w": xs1 - xs0, "h": ys1 - ys0, "z": v + dp})

mini = Image.fromarray(day).resize((448, 60), Image.LANCZOS)
mini.save(os.path.join(OUT, "minicarte.png"), optimize=True)

with open(os.path.join(MOD, "monde-data.js"), "w") as f:
    f.write("// Generated by tools/bake_world.py from village-art/A (compose3). Do not edit: re-run the script.\n")
    f.write(f"export const WORLD = {json.dumps({'w': W, 'h': H})};\n")
    f.write(f"export const TILES = {json.dumps(tiles)};\n")
    f.write("// front cut-outs: drawn above any unit whose depth (feet y + 3) is below z and that overlaps it\n")
    f.write("export const FRONTS = [\n" + ",\n".join("  " + json.dumps(fr) for fr in fronts) + "\n];\n")
print("ok", len(tiles), "tiles,", len(fronts), "fronts")
